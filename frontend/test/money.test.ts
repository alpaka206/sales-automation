import { describe, expect, it } from "vitest";
import { money } from "../src/screens/won/shared";

/** 금액 표기 — 기본은 원 단위, 분당 단가만 소수 둘째 자리.
 *
 * 단가는 금액 ÷ (크레딧 ÷ 60) 이라 딱 떨어지는 쪽이 드뭅니다. 2,630.89 를 2,631 로
 * 반올림해 보여 주면, 그 값을 다시 곱해 본 사람이 계약서의 금액과 안 맞는다고 생각합니다.
 * 서버는 늘 온전한 값을 내려주고(``won.unit_price``), 여기서는 표기만 자릅니다.
 */
describe("money", () => {
  it("계약 금액은 원 단위 — 소수점이 군더더기입니다", () => {
    expect(money(11_000_000)).toBe("₩11,000,000");
    expect(money(20_000, "USD")).toBe("$20,000");
    // 반올림은 그대로입니다. 자릿수를 안 주면 예전과 같은 글자가 나와야 합니다.
    expect(money(1100.6)).toBe("₩1,101");
  });

  it("분당 단가는 소수 둘째 자리까지", () => {
    // 서울대학교 계약: 20,000,000 ÷ (456,120 ÷ 60) = 2,630.8933…
    expect(money(2630.8933, "KRW", 2)).toBe("₩2,630.89");
    // 딱 떨어져도 자릿수를 채웁니다 — 목록에서 소수점 자리가 어긋나면 읽기 어렵습니다.
    expect(money(1450, "KRW", 2)).toBe("₩1,450.00");
    expect(money(20, "USD", 2)).toBe("$20.00");
  });

  it("값이 없으면 0 입니다 — 빈 칸이 NaN 으로 새지 않습니다", () => {
    expect(money(null)).toBe("₩0");
    expect(money("", "KRW", 2)).toBe("₩0.00");
  });
});
